import assert from 'node:assert/strict'

/** Execute against an authenticated, officially installed task app; no model or cloud requests. */
export async function runReferenceStorageJourney(page) {
  await page.click('button[aria-label="Plugins"]')
  await page.waitForSelector('[data-plugin-item="omnimux-reference-storage"]', { state: 'visible', timeout: 15000 })
  await page.click('[data-plugin-item="omnimux-reference-storage"]')
  await page.waitForSelector('[data-section="reference-storage"] input[aria-label="Upload endpoint"]', { state: 'visible' })
  await page.fill('input[aria-label="Upload endpoint"]', 'https://storage.example.test')
  await page.fill('input[aria-label="Storage bucket"]', 'reference-media')
  await page.fill('input[aria-label="Public read URL"]', 'https://media.example.test')
  await page.fill('input[aria-label="Access identifier"]', 'QA-ACCESS-NOT-REAL')
  await page.fill('input[aria-label="Secret access key"]', 'QA-SECRET-NOT-REAL')
  const enabled = await page.evaluate(() => document.querySelector('[data-section="reference-storage"] button[role="switch"]').getAttribute('aria-checked'))
  if (enabled !== 'true') await page.click('[data-section="reference-storage"] button[role="switch"]')
  await page.click('text="Save settings"')
  await page.waitForSelector('text="Saved for subsequent generation tasks"', { state: 'visible', timeout: 15000 })
  const cleared = await page.evaluate(() => ({ access: document.querySelector('input[aria-label="Access identifier"]').value, secret: document.querySelector('input[aria-label="Secret access key"]').value }))
  assert.equal(cleared.access, '')
  assert.equal(cleared.secret, '')
  const response = await page.fetch('/omnimux/reference-storage/config')
  assert.equal(response.status, 200)
  assert.equal(response.body.includes('QA-SECRET-NOT-REAL'), false)
  assert.equal(response.body.includes('QA-ACCESS-NOT-REAL'), false)
  const saved = JSON.parse(response.body)
  assert.equal(saved.config.enabled, true)
  assert.equal(saved.hasCredentials, true)
  await page.click('button[aria-label="Back to plugins"]')
  await page.click('[data-plugin-item="omnimux-reference-storage"]')
  await page.waitForFunction(() => document.querySelector('input[aria-label="Upload endpoint"]')?.value === 'https://storage.example.test', undefined, { timeout: 10000 })
  const reopened = await page.evaluate(() => ({ access: document.querySelector('input[aria-label="Access identifier"]').value, secret: document.querySelector('input[aria-label="Secret access key"]').value }))
  assert.equal(reopened.access, '')
  assert.equal(reopened.secret, '')
  await page.fill('input[aria-label="Upload endpoint"]', 'http://127.0.0.1')
  await page.click('text="Save settings"')
  await page.waitForSelector('[data-section="reference-storage"] [role="alert"]', { state: 'visible', timeout: 10000 })
  const rejected = await page.fetch('/omnimux/reference-storage/config')
  assert.equal(JSON.parse(rejected.body).config.endpoint, 'https://storage.example.test')
  return { pass: true, saved: true, credentialsRedacted: true, reopened: true, rejectedEditPreserved: true }
}
